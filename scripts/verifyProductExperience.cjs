const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');

require.extensions['.ts'] = (sourceModule, filename) => {
  const compiled = ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } });
  sourceModule._compile(compiled.outputText, filename);
};
const { prepareRequestDetails, prepareRequestAppointment } = require('../src/utils/requestDraft.ts');
const { resolveProfessionalVerification } = require('../src/utils/professionalVerification.ts');
const { resolveAvailabilityQuery } = require('../src/utils/professionalAvailability.ts');
const { prepareServiceIssue } = require('../src/utils/serviceIssue.ts');
const { ServiceIssue } = require('../src/config/serviceIssues.ts');
const { ProfessionalVerificationStatus, VerificationDocumentType, ServiceRequestFieldType } = require('../src/types/api.ts');
const draft = { description: 'Preciso consertar a torneira da cozinha.', answers: {}, address: 'Rua de teste, 10', city: 'Recife', state: 'pe', budgetMinimum: '100,50', budgetMaximum: '250,00', preferredDate: '', preferredTime: '' };
assert.equal(prepareRequestDetails(draft, []).description, draft.description);
assert.throws(() => prepareRequestDetails({ ...draft, description: 'Curto' }, []), /20 caracteres/);
assert.throws(() => prepareRequestDetails(draft, [{ key: 'area', label: 'Área', type: ServiceRequestFieldType.Number, required: true }]), /Área/);
assert.deepEqual(prepareRequestAppointment(draft), { address: draft.address, city: 'Recife', state: 'PE', budgetMinimum: 100.5, budgetMaximum: 250, preferredAt: undefined });
assert.equal(draft.state, 'pe');
assert.throws(() => prepareRequestAppointment({ ...draft, address: '' }), /rua/);
assert.throws(() => prepareRequestAppointment({ ...draft, budgetMinimum: '300' }), /máximo/);
assert.throws(() => prepareRequestAppointment({ ...draft, budgetMinimum: 'abc' }), /reais/);
const legacyProfessional = { verificationStatus: ProfessionalVerificationStatus.Verified };
assert.equal(resolveProfessionalVerification(legacyProfessional).identity, false);
assert.deepEqual(resolveProfessionalVerification({ verificationStatus: ProfessionalVerificationStatus.ProfessionalVerified, verifiedDocuments: [] }), { identity: false, address: false, certificate: false });
assert.equal(resolveProfessionalVerification({ verifiedDocuments: [VerificationDocumentType.Identity] }).identity, true);
assert.equal(resolveProfessionalVerification({ verifiedDocuments: [VerificationDocumentType.Identity] }).certificate, false);
const futureDate = new Date(Date.now() + 7 * 86400000).toISOString().slice(0, 10);
const availabilityQuery = new URLSearchParams(resolveAvailabilityQuery(futureDate, '09:00'));
assert.equal(availabilityQuery.get('availableAt'), `${futureDate}T12:00:00.000Z`);
assert.throws(() => resolveAvailabilityQuery(futureDate, ''), /data e o horário/);
assert.throws(() => resolveAvailabilityQuery('2000-01-01', '09:00'), /futuros/);
const delay = prepareServiceIssue(ServiceIssue.Delay, 'O profissional ainda não chegou ao local combinado.');
const absence = prepareServiceIssue(ServiceIssue.Absence, 'O profissional não compareceu ao horário combinado.');
assert.equal(delay.reason, 'service_not_performed');
assert.match(delay.description, /^\[Atraso\]/);
assert.match(absence.description, /^\[Não compareceu\]/);
assert.throws(() => prepareServiceIssue(ServiceIssue.Delay, 'curto'), /20 caracteres/);
assert.throws(() => prepareServiceIssue(ServiceIssue.Delay, 'x'.repeat(3000)), /2.900/);
process.stdout.write('Quick request, verification evidence, availability time zone and order support checks passed.\n');
